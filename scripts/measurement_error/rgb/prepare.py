"""RGB acquisition perturbations and their true camera/depth references.

object_warp: image-plane localization displacement at local GT depth, not depth noise.
camera_jitter: actual camera translation; RGB is generated by GPU render.py.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

import numpy as np

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT/"scripts"))


def inputs(config, only):
    import cv2
    from PIL import Image
    from measurement_error.rays import camera_records
    # rays imports Warp, so inputs are prepared in the WSL tool environment.
    spec, master = config["rgb_sweep"], Path(config["master"])
    scale = json.loads((master/"scale.json").read_text())["mm_per_source_unit"]
    records = camera_records(config, master)
    res = spec["resolution"]
    catalog = []
    for mode in spec["modes"]:
        if mode not in ("object_warp", "camera_jitter"):
            raise ValueError(mode)
        for rms in spec["rms_mm"]:
            for seed in config["seeds"]:
                name = f"{mode}_rms{rms:g}_s{seed}"
                scene = Path(spec["root"])/name
                catalog.append({"name": name, "scene": scene.as_posix(), "mode": mode,
                                "rms_mm": rms, "seed": seed})
                if only and name not in only:
                    continue
                (scene/"images").mkdir(parents=True, exist_ok=True)
                (scene/"masks").mkdir(exist_ok=True)
                rng = np.random.default_rng(seed)
                shifts = rng.normal(size=(len(records), 3))
                shifts *= rms/scale/max(float(np.sqrt((shifts**2).sum(1).mean())), 1e-12)
                rig, hashes, measured = [], {}, []
                for index, frame in enumerate(records):
                    item = dict(frame)
                    ratio = config["model_resolution"]/res
                    focal_original = frame["K_model"][0][0]/ratio
                    item.update(original_width=res, original_height=res,
                        K_original=[[focal_original, 0, (res-1)/2], [0, focal_original, (res-1)/2], [0, 0, 1]],
                        pixel_affine_original_to_model=[[ratio, 0, (ratio-1)/2], [0, ratio, (ratio-1)/2], [0, 0, 1]])
                    pose = np.linalg.inv(np.asarray(frame["T_world_to_cam"])) @ np.diag([1., -1., -1., 1.])
                    if mode == "camera_jitter":
                        pose[:3, 3] += shifts[index]
                        item["T_world_to_cam"] = np.linalg.inv(pose @ np.diag([1., -1., -1., 1.])).tolist()
                        measured.append(float(np.linalg.norm(shifts[index])*scale))
                    else:
                        rgba = np.asarray(Image.open(Path(config["rgb_source"])/frame["file"]).convert("RGBA"), dtype=np.float32)
                        alpha = rgba[..., 3]/255
                        rgb = rgba[..., :3]*alpha[..., None]+255*(1-alpha[..., None])
                        rgb = cv2.resize(rgb, (res, res), interpolation=cv2.INTER_AREA)
                        alpha = cv2.resize(alpha, (res, res), interpolation=cv2.INTER_AREA)
                        depth = np.load(master/"geometry/gt_ray/depth"/(Path(frame["file"]).stem+".npy"))
                        depth = cv2.resize(depth, (res, res), interpolation=cv2.INTER_NEAREST)
                        valid = (depth > 0) & (alpha > .5)
                        depth = np.where(depth > 0, depth, np.median(depth[depth > 0]))
                        field = rng.normal(size=(res, res, 2)).astype(np.float32)
                        field = cv2.GaussianBlur(field, (0, 0), spec["warp_correlation_pixels"])
                        field *= rms/max(float(np.sqrt((field[valid]**2).sum(1).mean())), 1e-12)
                        focal = frame["K_model"][0][0]*res/frame["model_width"]
                        pixels = field*focal/(depth[..., None]*scale)
                        yy, xx = np.indices((res, res), dtype=np.float32)
                        u, v = (xx-pixels[..., 0]).astype(np.float32), (yy-pixels[..., 1]).astype(np.float32)
                        rgb = cv2.remap(rgb, u, v, cv2.INTER_LINEAR, borderMode=cv2.BORDER_CONSTANT, borderValue=(255, 255, 255))
                        mask = cv2.remap(alpha, u, v, cv2.INTER_NEAREST, borderMode=cv2.BORDER_CONSTANT, borderValue=0)
                        target = scene/"images"/frame["file"]
                        Image.fromarray(np.rint(rgb).clip(0, 255).astype(np.uint8)).save(target)
                        Image.fromarray((mask > .5).astype(np.uint8)*255).save(scene/"masks"/frame["file"])
                        hashes[frame["file"]] = hashlib.sha256(target.read_bytes()).hexdigest()
                        measured.append(float(np.sqrt((field[valid]**2).sum(1).mean())))
                    item["c2w_blender"] = pose.tolist()
                    rig.append(item)
                manifest = {"mode": mode, "target_rms_mm": rms, "realized_rms_mm": float(np.sqrt(np.mean(np.square(measured)))),
                    "seed": seed, "input_order": [f["file"] for f in rig], "input_sha256": hashes,
                    "definition": "image-plane 2D displacement at nominal GT depth" if mode == "object_warp" else
                                  "3D actual camera-center translation; orientation held fixed; actual poses used for evaluation",
                    "config": config}
                previous = scene/"perturbation.json"
                if previous.exists() and mode == "camera_jitter":
                    old = json.loads(previous.read_text())
                    expected = {"resolution": res, "samples": spec["render_samples"], "seed": spec["render_seed"],
                                "denoising": False, "device": "GPU", "backend": "OPTIX"}
                    if old.get("render_options", expected) != expected:
                        raise ValueError("Rendering changed; choose a fresh rgb_sweep.root")
                    for key in ("input_sha256", "render_options", "devices", "render_seconds"):
                        if key in old:
                            manifest[key] = old[key]
                (scene/"rig.json").write_text(json.dumps({"frames": rig}, indent=2))
                (scene/"perturbation.json").write_text(json.dumps(manifest, indent=2))
                print("Prepared", name, flush=True)
    root = Path(spec["root"])
    root.mkdir(parents=True, exist_ok=True)
    (root/"catalog.json").write_text(json.dumps(catalog, indent=2)+"\n")


def ground_truth(config, only):
    import warp as wp
    from measurement_error.rays import cast
    wp.init()
    device = wp.get_device("cuda:0")
    assert device.is_cuda
    source = np.load(Path(config["master"])/"source_mesh.npz")
    mesh = wp.Mesh(points=wp.array(source["vertices"], dtype=wp.vec3, device=device),
                   indices=wp.array(source["faces"].ravel(), dtype=wp.int32, device=device))
    for row in json.loads((Path(config["rgb_sweep"]["root"])/"catalog.json").read_text()):
        if only and row["name"] not in only:
            continue
        scene = Path(row["scene"])
        if not (scene/"rig.json").exists():
            continue
        records = json.loads((scene/"rig.json").read_text())["frames"]
        folder = scene/"geometry/gt"
        for name in ("depth", "foreground"):
            (folder/name).mkdir(parents=True, exist_ok=True)
        for frame in records:
            k, t = np.array(frame["K_model"]), np.array(frame["T_world_to_cam"])
            rotation = t[:3, :3].T.astype(np.float32)
            origin = (-rotation @ t[:3, 3]).astype(np.float32)
            shape = (frame["model_height"], frame["model_width"])
            values = wp.zeros(shape, dtype=wp.float32, device=device)
            wp.launch(cast, dim=shape, inputs=[mesh.id, wp.vec3(*origin), wp.mat33(rotation),
                float(k[0, 0]), float(k[1, 1]), float(k[0, 2]), float(k[1, 2])], outputs=[values], device=device)
            depth = values.numpy()
            stem = Path(frame["file"]).stem
            np.save(folder/"depth"/f"{stem}.npy", depth)
            np.save(folder/"foreground"/f"{stem}.npy", depth > 0)
        (folder/"cameras.json").write_text(json.dumps({"camera_model": "PINHOLE", "frames": records}, indent=2))
        print("GPU GT", row["name"], flush=True)


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--config", default="configs/experiments/measurement_error.json")
    p.add_argument("--phase", choices=["inputs", "gt"], required=True)
    p.add_argument("--only")
    args = p.parse_args()
    {"inputs": inputs, "gt": ground_truth}[args.phase](json.loads(Path(args.config).read_text()),
        set(args.only.split(",")) if args.only else None)
